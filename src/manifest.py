"""source_manifest.json / .md: where the data came from, what was written, and with what command.

Everything here is a pure function of the output directory and the run arguments: the file
list is sorted, there are no timestamps or absolute paths, so the manifest itself is
reproducible. It is written last, and covers every file except itself.
"""
from __future__ import annotations

import hashlib
import json
import platform
import sqlite3
from pathlib import Path

import numpy as np
import pandas as pd

SYNTHETIC_STATEMENT = ("All data in this dataset is synthetic. It is generated by this repository's code from a fixed "
                       "random seed. No real company, bank, customer, transaction or market-data source was used, "
                       "downloaded or copied. The FX rates are a seeded random walk, not market rates.")


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


# What the generator owns. Output of later steps (exceptions/, validation/, evaluation/) may sit in the same
# directory but is not part of the generated dataset, and re-running the generator must not pick it up.
GENERATED = ("input", "json", "sql", "db", "derived", "ground_truth", "run_config.json", "generator_command.txt")


def list_files(root: Path) -> list[Path]:
    found = []
    for top in GENERATED:
        p = root / top
        found += [p] if p.is_file() else sorted(q for q in p.rglob("*") if q.is_file()) if p.is_dir() else []
    return sorted(found, key=lambda q: q.relative_to(root).as_posix())


def build_manifest(root: Path, command: str, config, table_rows: dict[str, int]) -> dict:
    files = [{"path": p.relative_to(root).as_posix(), "bytes": p.stat().st_size, "sha256": sha256_file(p)}
             for p in list_files(root)]
    return {
        "dataset": "synthetic liquidity-forecasting dataset",
        "synthetic": True,
        "external_sources": [],
        "statement": SYNTHETIC_STATEMENT,
        "generator_command": command,
        "seed": config.seed,
        "scale": config.scale_name,
        "config_fingerprint": config.fingerprint(),
        "environment": {"python": platform.python_version(), "numpy": np.__version__, "pandas": pd.__version__,
                        "sqlite": sqlite3.sqlite_version},
        "tables": [{"name": k, "rows": int(v)} for k, v in table_rows.items()],
        "files": files,
    }


def manifest_markdown(m: dict) -> str:
    L = ["# Source manifest", "", m["statement"], "", "External sources: none.", "",
         f"Generator command: `{m['generator_command']}`", "",
         f"Seed {m['seed']}, scale `{m['scale']}`, config fingerprint `{m['config_fingerprint'][:16]}`. "
         f"Python {m['environment']['python']}, numpy {m['environment']['numpy']}, pandas {m['environment']['pandas']}, "
         f"SQLite {m['environment']['sqlite']}.", "", "## Tables", "", "| Table | Rows |", "|---|---|"]
    L += [f"| {t['name']} | {t['rows']:,} |" for t in m["tables"]]
    L += ["", "## Files", "", "| File | Bytes | SHA-256 |", "|---|---|---|"]
    L += [f"| {f['path']} | {f['bytes']:,} | `{f['sha256']}` |" for f in m["files"]]
    return "\n".join(L) + "\n"


def write_manifest(root: Path, command: str, config, table_rows: dict[str, int]) -> Path:
    (root / "generator_command.txt").write_text(command + "\n", encoding="utf-8", newline="\n")
    m = build_manifest(root, command, config, table_rows)
    path = root / "source_manifest.json"
    path.write_text(json.dumps(m, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
    (root / "source_manifest.md").write_text(manifest_markdown(m), encoding="utf-8", newline="\n")
    return path
